// Generates src/polychrony/instance.generated.js: createInstance(), which
// makes a complete, independent timeline (core and temporal) each time it's
// called.
//
// The main timeline's code stays exactly as written, in module scope, so
// polychrony costs it nothing. A timeline needs its own copy of every
// module-level variable, so this bundles core and temporal into one scope
// and wraps that scope in a plain arrow function. Calling the function runs
// the code again with fresh variables: no `new`, no constructors.
//
// Run by npm run build and by the polychrony tests. The output is ignored by
// git, and Rollup bundles it into dist/js/soucouyant-polychrony.js.
import { rollup } from 'rollup'
import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const source = (path) => fileURLToPath(new URL(`../src/${path}`, import.meta.url))
const entry = source('polychrony/instance-entry.js')
const environment = source('environment.js')
const instanceEnvironment = source('polychrony/instance-environment.js')
const output = source('polychrony/instance.generated.js')

// Inside a timeline, every import of environment.js gets the stand-in, which
// carries the parent's session start
const substituteEnvironment = {
  name: 'instance-environment',
  resolveId: (importee, importer) => {
    if (importer === undefined || importer === instanceEnvironment || !importee.startsWith('.')) return null
    return resolve(dirname(importer), importee) === environment ? instanceEnvironment : null
  }
}

const bundle = await rollup({ input: entry, plugins: [substituteEnvironment], onwarn: (warning, warn) => warn(warning) })
const { output: [chunk] } = await bundle.generate({ format: 'es' })
await bundle.close()

if (chunk.imports.length !== 0) throw new Error(`A timeline must be self-contained, but it imports ${chunk.imports.join(', ')}`)

// Rollup ends an ES bundle with one export statement; it becomes the
// function's return value
const exportPattern = /\nexport \{([^}]*)\};?\s*$/
const match = exportPattern.exec(chunk.code)
if (match === null) throw new Error('Expected the bundle to end with a single export statement')
const exported = match[1].split(',').map((entry) => entry.trim()).filter(Boolean).map((entry) => {
  const [local, name = local] = entry.split(/\s+as\s+/)
  return local === name ? local : `${name}: ${local}`
})

// Not indented: indenting would change any template string spanning lines.
// The stand-in environment's global comment goes: inside the function,
// instanceSeed is the parameter
const body = chunk.code.slice(0, match.index).replace(/\/\* global instanceSeed \*\/\n?/g, '')

await writeFile(output, `// Generated by scripts/build-instance.js from src/polychrony/instance-entry.js.
// Do not edit: npm run build and npm test regenerate it.

// Makes one complete, independent timeline: its own registry, values,
// subscribers, locks, history and head, running the same code as the main
// timeline. instanceSeed carries what a timeline inherits from its parent.
export const createInstance = (instanceSeed) => {
${body}

  return { ${exported.join(', ')} }
}
`)
